import React, { useState } from 'react';
import {
  Wrench,
  CheckCircle2,
  AlertTriangle,
  RotateCcw,
  Check,
  Copy,
  Download,
  FileCode,
  Shield,
  ThumbsUp,
  Cpu
} from 'lucide-react';
import { Finding, RemediationProposal } from '../types';
import { SeverityBadge, StatusBadge } from '../components/SeverityBadge';
import { DiffViewer } from '../components/DiffViewer';
import { handleRemediationAction } from '../services/api';

interface RemediationPageProps {
  findings: Finding[];
  selectedFinding?: Finding | null;
  onRefreshFindings: () => void;
}

export const RemediationPage: React.FC<RemediationPageProps> = ({
  findings,
  selectedFinding,
  onRefreshFindings
}) => {
  const findingsWithRemediation = findings.filter(f => f.remediation);

  const [activeFindingId, setActiveFindingId] = useState<string>(
    selectedFinding?.id || (findingsWithRemediation[0]?.id || '')
  );
  const [copied, setCopied] = useState(false);
  const [actionLoading, setActionLoading] = useState(false);
  const [feedbackMessage, setFeedbackMessage] = useState<string | null>(null);

  const currentFinding = findingsWithRemediation.find(f => f.id === activeFindingId);
  const remediation = currentFinding?.remediation;

  const triggerAction = async (action: 'approve' | 'apply' | 'rollback' | 'reject') => {
    if (!remediation) return;
    setActionLoading(true);
    try {
      const res = await handleRemediationAction(remediation.id, action);
      setFeedbackMessage(res.message);
      onRefreshFindings();
      setTimeout(() => setFeedbackMessage(null), 3000);
    } catch (err: any) {
      alert(err.message || 'Action failed');
    } finally {
      setActionLoading(false);
    }
  };

  const downloadDiff = () => {
    if (!remediation) return;
    const blob = new Blob([remediation.diff], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `patch_${currentFinding?.rule_id || 'remediation'}.diff`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-bold text-white flex items-center gap-2">
            <Wrench className="w-5 h-5 text-cyan-400" />
            The Surgeon: Fail-Safe Remediation Workspace
          </h1>
          <p className="text-xs text-cyber-muted">
            Inspect, validate, and apply context-aware code patches generated by Agent 7. Automated AST grammar checks and pre-fix snapshot guards ensure fail-safe deployment.
          </p>
        </div>

        {feedbackMessage && (
          <div className="p-2.5 bg-emerald-500/15 border border-emerald-500/30 rounded-lg text-emerald-400 text-xs flex items-center gap-2 animate-fadeIn">
            <CheckCircle2 className="w-4 h-4 shrink-0" />
            <span>{feedbackMessage}</span>
          </div>
        )}
      </div>

      {findingsWithRemediation.length === 0 ? (
        <div className="p-12 rounded-xl bg-cyber-card border border-cyber-border text-center space-y-3">
          <Shield className="w-10 h-10 text-cyan-400 mx-auto" />
          <h2 className="text-base font-bold text-white">No Remediation Proposals Generated Yet</h2>
          <p className="text-xs text-cyber-muted max-w-md mx-auto">
            Run a security scan with the Security Scanner. When vulnerabilities are detected, Agent 7 synthesizes safe, validated code patches.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-4 gap-6">
          {/* Proposal Selector Sidebar (1 col) */}
          <div className="space-y-3">
            <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 px-1">
              Patches ({findingsWithRemediation.length})
            </h3>

            <div className="space-y-2">
              {findingsWithRemediation.map((f) => {
                const isSelected = f.id === activeFindingId;
                const rem = f.remediation!;

                return (
                  <button
                    key={f.id}
                    onClick={() => setActiveFindingId(f.id)}
                    className={`w-full p-3 rounded-lg border text-left transition-all space-y-1.5 ${
                      isSelected
                        ? 'bg-cyan-500/15 border-cyan-400 text-white shadow-sm'
                        : 'bg-cyber-card border-cyber-border hover:border-slate-600 text-slate-300'
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <SeverityBadge severity={f.severity} />
                      <StatusBadge status={rem.status} />
                    </div>
                    <div className="text-xs font-bold truncate">{f.title}</div>
                    <div className="text-[10px] text-cyber-muted font-mono">{f.rule_id} • Line {f.line_start}</div>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Remediation Workspace Detail (3 cols) */}
          {currentFinding && remediation && (
            <div className="lg:col-span-3 space-y-5">
              {/* Proposal Header Banner */}
              <div className="p-5 rounded-xl bg-cyber-card border border-cyber-border space-y-4">
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                  <div>
                    <div className="flex items-center gap-2 mb-1">
                      <SeverityBadge severity={currentFinding.severity} score={currentFinding.numeric_score} />
                      <StatusBadge status={remediation.status} />
                      <span className="text-xs font-mono text-cyan-400">{currentFinding.rule_id}</span>
                    </div>
                    <h2 className="text-lg font-bold text-white">{currentFinding.title}</h2>
                  </div>

                  {/* Patch Actions */}
                  <div className="flex items-center gap-2">
                    {remediation.status === 'suggested' && (
                      <button
                        disabled={actionLoading}
                        onClick={() => triggerAction('approve')}
                        className="px-3.5 py-1.5 rounded-lg bg-amber-500 hover:bg-amber-400 text-black font-semibold text-xs transition-colors flex items-center gap-1.5"
                      >
                        <ThumbsUp className="w-3.5 h-3.5" /> Approve Patch
                      </button>
                    )}

                    {(remediation.status === 'approved' || remediation.status === 'suggested') && (
                      <button
                        disabled={actionLoading || !remediation.syntax_valid}
                        onClick={() => triggerAction('apply')}
                        className="px-4 py-1.5 rounded-lg bg-emerald-500 hover:bg-emerald-400 text-black font-extrabold text-xs transition-colors flex items-center gap-1.5 shadow-md shadow-emerald-500/20"
                      >
                        <Check className="w-3.5 h-3.5" /> Apply Patch
                      </button>
                    )}

                    {remediation.status === 'applied' && (
                      <button
                        disabled={actionLoading}
                        onClick={() => triggerAction('rollback')}
                        className="px-3.5 py-1.5 rounded-lg bg-red-500/20 hover:bg-red-500/30 text-red-300 border border-red-500/30 font-semibold text-xs transition-colors flex items-center gap-1.5"
                      >
                        <RotateCcw className="w-3.5 h-3.5" /> Rollback to Original
                      </button>
                    )}
                  </div>
                </div>

                {/* Fail-Safe Safeguards Info */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs">
                  <div className="p-3 rounded-lg bg-[#0d1628] border border-cyber-border/60 flex items-center gap-2.5">
                    <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
                    <div>
                      <span className="font-semibold text-white block">AST Syntax Validation</span>
                      <span className="text-[11px] text-cyber-muted">{remediation.validation_message}</span>
                    </div>
                  </div>

                  <div className="p-3 rounded-lg bg-[#0d1628] border border-cyber-border/60 flex items-center gap-2.5">
                    <Shield className="w-4 h-4 text-cyan-400 shrink-0" />
                    <div>
                      <span className="font-semibold text-white block">Pre-Fix Snapshot Guard</span>
                      <span className="text-[11px] text-cyber-muted">Full backup stored. Revert anytime with zero risk.</span>
                    </div>
                  </div>
                </div>

                {/* Explanation */}
                <div className="p-3.5 rounded-lg bg-[#0e1628] border border-cyber-border text-xs text-slate-300 space-y-1">
                  <span className="text-cyan-400 font-bold block">Security Improvement Rationale:</span>
                  <p>{remediation.explanation}</p>
                </div>
              </div>

              {/* Code Diff Display */}
              <div className="space-y-3">
                <div className="flex items-center justify-between">
                  <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-1.5">
                    <FileCode className="w-4 h-4 text-cyan-400" />
                    Unified Remediation Diff ({remediation.file_path})
                  </h3>

                  <div className="flex items-center gap-2">
                    <button
                      onClick={() => {
                        navigator.clipboard.writeText(remediation.proposed_code);
                        setCopied(true);
                        setTimeout(() => setCopied(false), 1500);
                      }}
                      className="px-2.5 py-1 text-xs text-cyber-muted hover:text-white rounded border border-cyber-border bg-[#0e1628] flex items-center gap-1"
                    >
                      {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                      <span>{copied ? 'Copied' : 'Copy Proposed'}</span>
                    </button>

                    <button
                      onClick={downloadDiff}
                      className="px-2.5 py-1 text-xs text-cyber-muted hover:text-white rounded border border-cyber-border bg-[#0e1628] flex items-center gap-1"
                    >
                      <Download className="w-3.5 h-3.5" />
                      <span>Download .diff</span>
                    </button>
                  </div>
                </div>

                <DiffViewer diff={remediation.diff} />
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
